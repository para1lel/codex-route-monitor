# An OS schedule for the monitor, for a machine whose magpie may be closed
# when a slot comes: two Windows Scheduled Tasks, both calling
# `scan --scope auto`, which does nothing unless the schedule says a slot is
# due (so nothing runs between slots).
#
# Both tasks start through a .vbs shim: wscript.exe is a windowed program and
# the shim asks for window style 0, so a scan — which can run for minutes —
# never puts a console on screen.
#
#   powershell -NoProfile -ExecutionPolicy Bypass -File scripts/install-schedule.ps1
#   ... -Cli <path to bin\codex-route-monitor.mjs> -Node <path to node.exe>
#   ... -Uninstall
#   ... -DryRun      say what would be registered

param(
    [string]$Cli = "",
    [string]$Node = "",
    [switch]$Uninstall,
    [switch]$DryRun
)

$ErrorActionPreference = "Stop"

$TaskNames = @("CodexRouteMonitor-Daily", "CodexRouteMonitor-Enabled")
# the every-three-hours task this replaces, removed so it stops firing
$OldTaskNames = @("CodexRouteMonitor-3-Hourly")

function Remove-Tasks {
    foreach ($name in ($TaskNames + $OldTaskNames)) {
        $existing = Get-ScheduledTask -TaskName $name -ErrorAction SilentlyContinue
        if (-not $existing) {
            Write-Host "not there: $name"
            continue
        }
        if ($DryRun) {
            Write-Host "would remove: $name"
            continue
        }
        Unregister-ScheduledTask -TaskName $name -Confirm:$false
        Write-Host "removed: $name"
    }
}

if ($Uninstall) {
    Remove-Tasks
    exit 0
}

if (-not $Node) {
    $found = Get-Command node -ErrorAction SilentlyContinue
    if (-not $found) { throw "node was not found; pass -Node <path to node.exe>" }
    $Node = $found.Source
}
if (-not $Cli) {
    $Cli = Join-Path (Split-Path -Parent $PSScriptRoot) "bin\codex-route-monitor.mjs"
}
if (-not (Test-Path $Cli)) { throw "the monitor's command line was not found at $Cli" }

# wscript.exe is a windowed program: the scan it starts gets window style 0 and
# no console ever appears, however long the scan runs. The launcher lives in the
# monitor's state folder, not in the plugin folder: `magpie plugin update`
# replaces the plugin folder, and a task pointing into it would fail with
# "run-hidden.vbs not found" until something wrote it again.
$stateDir = if ($env:CODEX_ROUTE_MONITOR_HOME) { $env:CODEX_ROUTE_MONITOR_HOME } else { Join-Path $env:USERPROFILE ".config\magpie\codex-route-monitor" }
$vbs = Join-Path $stateDir "run-hidden.vbs"
$vbsBody = @"
' Generated by codex-route-monitor: run a scan with no console window.
Dim shell, args, i
Set shell = CreateObject("WScript.Shell")
args = ""
For i = 0 To WScript.Arguments.Count - 1
  args = args & " " & Chr(34) & WScript.Arguments(i) & Chr(34)
Next
shell.Run """$Node"" ""$Cli""" & args, 0, False
"@
if ($DryRun) {
    Write-Host "would write: $vbs"
} else {
    Set-Content -Path $vbs -Value $vbsBody -Encoding ASCII
    Write-Host "wrote: $vbs"
}

$action = New-ScheduledTaskAction -Execute "wscript.exe" -Argument "`"$vbs`" scan --scope auto --trigger os"
$settings = New-ScheduledTaskSettingsSet `
    -StartWhenAvailable `
    -AllowStartIfOnBatteries `
    -DontStopIfGoingOnBatteries `
    -MultipleInstances IgnoreNew `
    -Hidden `
    -ExecutionTimeLimit (New-TimeSpan -Hours 3)

$dailyTrigger = New-ScheduledTaskTrigger -Daily -At "00:00"
$morningTrigger = New-ScheduledTaskTrigger -Daily -At "08:00"
$afternoonTrigger = New-ScheduledTaskTrigger -Daily -At "16:00"

$tasks = @(
    @{ Name = $TaskNames[0]; Triggers = @($dailyTrigger); Description = "Codex route monitor: every Codex account at midnight (magpie-codex-route-monitor)" },
    @{ Name = $TaskNames[1]; Triggers = @($morningTrigger, $afternoonTrigger); Description = "Codex route monitor: the Codex accounts in use, at 08:00 and 16:00 (magpie-codex-route-monitor)" }
)

# the every-three-hours task has no place in the 08:00/16:00 schedule
$old = Get-ScheduledTask -TaskName $OldTaskNames[0] -ErrorAction SilentlyContinue
if ($old -and -not $DryRun) {
    Unregister-ScheduledTask -TaskName $OldTaskNames[0] -Confirm:$false
    Write-Host "removed: $($OldTaskNames[0])"
}

foreach ($task in $tasks) {
    $when = ($task.Triggers | ForEach-Object { $_.StartBoundary.Substring(11, 5) }) -join " and "
    $line = "wscript `"$vbs`" scan --scope auto --trigger os  ($($task.Name) at $when, hidden)"
    if ($DryRun) {
        Write-Host "would register: $line"
        continue
    }
    Register-ScheduledTask -TaskName $task.Name -Action $action -Trigger $task.Triggers -Settings $settings -Description $task.Description -Force | Out-Null
    Write-Host "registered: $line"
}

if (-not $DryRun) {
    Write-Host ""
    Write-Host "Both tasks run only when a slot is due (midnight, 08:00, 16:00); see:"
    Write-Host "  schtasks /Query /TN $($TaskNames[0]) /V /FO LIST"
    Write-Host "  schtasks /Query /TN $($TaskNames[1]) /V /FO LIST"
    Write-Host "  node `"$Cli`" schedule"
}
